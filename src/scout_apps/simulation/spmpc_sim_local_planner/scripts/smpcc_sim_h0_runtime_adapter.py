def read_development_event(path: Path, record_type: str, case_manifest_hash: str, time_key: str) -> Mapping[str, Any]:
    event = read_json(path, "H0 development event")
    require(event.get("record_type") == record_type, "H0 development event has wrong record_type")
    require(event.get("status") == "PASS", "H0 development event is not PASS")
