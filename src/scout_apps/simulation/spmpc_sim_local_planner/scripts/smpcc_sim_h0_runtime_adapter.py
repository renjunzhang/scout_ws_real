def resolve_development_liquid_plant(args: argparse.Namespace) -> Optional[Dict[str, Any]]:
    """Resolve the explicit opt-in without changing normal H0 semantics."""
    enabled = bool(getattr(args, "with_development_liquid_plant", False))
    configured = getattr(args, "development_liquid_plant_config", None)
    require(enabled or configured is None, "--development-liquid-plant-config requires --with-development-liquid-plant")
    if not enabled:
        return None
    return development_liquid_plant_capability(
        Path(configured) if configured is not None else LIQUID_PLANT_DEFAULT_CONFIG
    )


