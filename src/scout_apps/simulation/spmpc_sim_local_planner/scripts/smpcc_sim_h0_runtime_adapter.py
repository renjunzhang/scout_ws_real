def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)

    item = sub.add_parser("describe", help="print the immutable H0-only adapter identity")
    item.set_defaults(func=command_describe)
    item = sub.add_parser("self-check", help="validate static H0 adapter assets without ROS/Gazebo")
    item.set_defaults(func=command_self_check)
    item = sub.add_parser("prepare", help="write an H0-only row, assets and single-row run spec below /data")
    item.add_argument("--output-root", type=Path, required=True)
    item.add_argument("--spec-output", type=Path, required=True)
    item.add_argument("--ros-master-uri", required=True)
    item.add_argument("--gazebo-master-uri", required=True)
    item.add_argument("--tail-sec", type=float, default=5.0)
    item.add_argument("--startup-timeout-sec", type=float, default=120.0)
    # ``ready`` has a single 90-second pre-motion global budget.  Leave enough
    # outer command allowance for process startup/teardown instead of racing
    # the runner's watchdog at the exact same deadline.  This does not alter
    # the fixed 60-second effective-motion/GOAL_REACHED deadline.
    item.add_argument("--command-timeout-sec", type=float, default=105.0)
    item.add_argument("--recorder-ready-timeout-sec", type=float, default=15.0)
    item.add_argument("--ready-timeout-sec", type=float, default=90.0)
    item.add_argument("--goal-probe-timeout-sec", type=float, default=0.75)
    item.add_argument("--visualize", action="store_true", help="development-only Gazebo + tracking RViz; never formal evidence")
    item.add_argument(
        "--with-development-liquid-plant",
        action="store_true",
        help="explicit H0-only UNVALIDATED independent plant; record-only and never physical-primary",
    )
    item.add_argument(
        "--development-liquid-plant-config",
        type=Path,
        default=None,
        help="checked-in C1/C2 *_development_unvalidated.yaml; requires --with-development-liquid-plant",
    )
    item.set_defaults(func=command_prepare)

    item = sub.add_parser("launch", help="start fresh H0 environment only")
    add_runtime_arguments(item)
    item.add_argument("--visualize", action="store_true", help="development-only Gazebo + tracking RViz; never formal evidence")
    item.set_defaults(func=command_launch)
    item = sub.add_parser("ready", help="check H0 environment topics/TF")
    add_runtime_arguments(item)
    item.add_argument("--timeout-sec", type=float, default=20.0)
    item.set_defaults(func=command_ready)
    item = sub.add_parser(
        "firewall-snapshot",
        help="write one live development-only controller subscriber-firewall snapshot",
    )
    add_runtime_arguments(item)
    item.add_argument("--checkpoint", required=True, choices=H0_DEVELOPMENT_FIREWALL_CHECKPOINTS)
    item.set_defaults(func=command_firewall_snapshot)
    item = sub.add_parser("recorder", help="record H0 topics to a case-local .bag.active artifact")
    add_runtime_arguments(item)
    item.add_argument("--artifact", type=Path, required=True)
    item.set_defaults(func=command_recorder)
    item = sub.add_parser("motion", help="start H0 B_smooth runtime s-curve only after recorder readiness")
    add_runtime_arguments(item)
    item.set_defaults(func=command_motion)
    item = sub.add_parser("motion-start-probe", help="wait for adapter-observed executed /odom motion")
    add_runtime_arguments(item)
    item.add_argument("--timeout-sec", type=float, default=20.0)
    item.set_defaults(func=command_motion_start_probe)
    item = sub.add_parser("goal-probe", help="emit GOAL_REACHED only for exact SPMPC status")
    add_runtime_arguments(item)
    item.add_argument("--timeout-sec", type=float, default=0.75)
    item.set_defaults(func=command_goal_probe)
    item = sub.add_parser("stop", help="best-effort H0 zero Twist; not a formal acknowledgement")
    add_runtime_arguments(item)
    item.set_defaults(func=command_stop)

    item = sub.add_parser(
        "effective-config-readback",
        help="offline-only H0 audit from a finalized rosbag; never formal evidence",
    )
    item.add_argument("--case-dir", required=True, type=Path)
    item.add_argument("--case-manifest", required=True, type=Path)
    item.add_argument("--case-manifest-sha256", default=None)
    item.add_argument("--bag", required=True, type=Path)
    item.add_argument("--declared-config", required=True, type=Path)
    item.add_argument("--output", required=True, type=Path)
    item.set_defaults(func=command_effective_config_readback)
    return parser


def main(argv: Optional[Iterable[str]] = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        return int(args.func(args))
    except AdapterError as exc:
        print(json.dumps({"status": "FAIL", "adapter_id": ADAPTER_ID, "formal": False, "error": str(exc)}, ensure_ascii=False, sort_keys=True), file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
