def derive_seed(seed_text: str, *parts: str) -> int:
    raw = "\x1f".join((seed_text,) + tuple(parts)).encode("utf-8")
    return int(hashlib.sha256(raw).hexdigest()[:16], 16)


def stable_trace(seed: int, stream: str) -> Dict[str, Any]:
    generator = random.Random(seed)
    samples = [
        {"time_index_ms": index * 2000, "unit_uniform": round(generator.random(), 12)}
        for index in range(31)
    ]
    core = {"stream": stream, "time_indexed": True, "samples": samples}
    return dict(core, trace_hash=canonical_hash(core), sample_count=len(samples))


