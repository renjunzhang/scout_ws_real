class AdapterError(RuntimeError):
    """A fail-closed H0 adapter contract error."""


def require(condition: bool, message: str) -> None:
    if not condition:
        raise AdapterError(message)


def canonical_bytes(value: Any) -> bytes:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode("utf-8")


def canonical_hash(value: Any) -> str:
    return hashlib.sha256(canonical_bytes(value)).hexdigest()


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def read_json(path: Path, label: str) -> Mapping[str, Any]:
    try:
        with path.open(encoding="utf-8") as stream:
            value = json.load(stream)
    except FileNotFoundError as exc:
        raise AdapterError(f"{label} is missing: {path}") from exc
    except json.JSONDecodeError as exc:
        raise AdapterError(f"{label} is not valid JSON: {path}: {exc}") from exc
    require(isinstance(value, Mapping), f"{label} must be a JSON object: {path}")
    return value


def ensure_within(path: Path, root: Path, label: str) -> Path:
    resolved = path.resolve()
    try:
        resolved.relative_to(root.resolve())
    except ValueError as exc:
        raise AdapterError(f"{label} must be below {root}: {resolved}") from exc
    return resolved


def write_json_once_or_same(path: Path, value: Mapping[str, Any]) -> None:
    """Create small development metadata without replacing prior evidence."""
    payload = json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
    path.parent.mkdir(parents=True, exist_ok=True)
    try:
        with path.open("x", encoding="utf-8") as stream:
            stream.write(payload)
    except FileExistsError:
        existing = read_json(path, "existing development artifact")
        require(canonical_hash(existing) == canonical_hash(value), f"refusing to replace differing development artifact: {path}")


def write_json_new(path: Path, value: Mapping[str, Any]) -> None:
    """Create immutable case evidence once; a failed audit is still evidence.

    Unlike ``write_json_once_or_same``, a readback receipt may not be replayed
    over an existing file, even if a caller happens to produce identical JSON.
    This prevents a later bag or declaration from being substituted for an
    earlier audit under the same case directory.
    """
    payload = json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
    path.parent.mkdir(parents=True, exist_ok=True)
    try:
        with path.open("x", encoding="utf-8") as stream:
            stream.write(payload)
    except FileExistsError as exc:
        raise AdapterError(f"immutable readback evidence already exists: {path}") from exc
    os.chmod(path, 0o444)


def canonical_uri(value: str, label: str) -> str:
    raw = value.strip()
    require(raw, f"{label} is required")
    if "://" not in raw:
        raw = "http://" + raw
    parsed = urlparse(raw)
    require(parsed.scheme == "http", f"{label} must use http://host:port")
    require(parsed.hostname is not None and parsed.port is not None, f"{label} must include host and port")
    require(parsed.path in ("", "/") and not parsed.params and not parsed.query and not parsed.fragment, f"{label} must not include a path/query")
    return f"http://{parsed.hostname}:{parsed.port}"


def resolve_runtime_uris(args: argparse.Namespace) -> Tuple[str, str]:
    env_ros = os.environ.get("ROS_MASTER_URI", "")
    env_gazebo = os.environ.get("GAZEBO_MASTER_URI", "")
    ros = canonical_uri(args.ros_master_uri or env_ros, "ROS master URI")
    gazebo = canonical_uri(args.gazebo_master_uri or env_gazebo, "Gazebo master URI")
    if env_ros:
        require(canonical_uri(env_ros, "ROS_MASTER_URI") == ros, "explicit ROS URI differs from runner ROS_MASTER_URI")
    if env_gazebo:
        require(canonical_uri(env_gazebo, "GAZEBO_MASTER_URI") == gazebo, "explicit Gazebo URI differs from runner GAZEBO_MASTER_URI")
    return ros, gazebo


