def _load_development_liquid_plant_config(config_path: Path) -> Tuple[Path, Mapping[str, Any]]:
    """Load only the two checked-in, explicitly unvalidated H0 templates.

    This is intentionally stricter than accepting an arbitrary YAML file.
    An arbitrary external configuration could claim a different condition or
    a different truth status while still being launched through the same H0
    command.  The development package's C1/C2 templates are the only allowed
    opt-in assets, and neither is a formal C1/C2 release.
    """
    config = ensure_within(Path(config_path), LIQUID_PLANT_CONFIG_ROOT, "development liquid-plant config")
    require(config.name in LIQUID_PLANT_ALLOWED_CONFIG_NAMES, "development liquid-plant config must be a checked-in C1/C2 UNVALIDATED template")
    require(config.is_file(), f"development liquid-plant config is missing: {config}")
    try:
        import yaml  # type: ignore
    except ImportError as exc:
        raise AdapterError("PyYAML is required to validate the development liquid-plant template") from exc
    try:
        with config.open(encoding="utf-8") as stream:
            raw = yaml.safe_load(stream)
    except (OSError, yaml.YAMLError) as exc:
        raise AdapterError(f"development liquid-plant config is unreadable YAML: {config}: {exc}") from exc
    require(isinstance(raw, Mapping), "development liquid-plant config must be a YAML object")
    expected = {
        "development_only": True,
        "formal": False,
        "fidelity_validation_status": "UNVALIDATED",
        "odom_topic": "/odom",
        "height_topic": "/sim_truth/liquid_height",
        "state_topic": "/sim_truth/liquid_state",
        "metadata_topic": "/sim_truth/liquid_metadata",
    }
    for key, value in expected.items():
        require(raw.get(key) == value, f"development liquid-plant config {key} must remain {value!r}")
    template_id = raw.get("condition_template_id")
    require(isinstance(template_id, str) and template_id.endswith("_DEVELOPMENT_TEMPLATE_UNFROZEN"), "development liquid-plant config must identify an unfrozen template")
    return config, raw


