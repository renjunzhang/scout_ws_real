def development_firewall_snapshot_path(case_dir: Path, checkpoint: str) -> Path:
    """Return one immutable, directly case-local firewall snapshot path."""
    require(
        checkpoint in H0_DEVELOPMENT_FIREWALL_CHECKPOINTS,
        f"unsupported H0 development firewall checkpoint: {checkpoint}",
    )
    case = ensure_within(case_dir, SIM_ROOT, "H0 firewall case directory")
    path = ensure_within(
        case / f"{H0_DEVELOPMENT_FIREWALL_FILE_PREFIX}{checkpoint}.json",
        case,
        "H0 firewall snapshot",
    )
    require(path.parent == case, "H0 firewall snapshot must be directly case-local")
    return path


