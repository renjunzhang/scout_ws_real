def publish_zero(environment: Mapping[str, str], timeout_sec: float = 5.0) -> bool:
    """Publish a bounded zero Twist using wall time, never simulated time.

    ``rostopic pub -1`` can wait for its default subscriber handshake long
    enough to race the frozen tail transition.  This tiny, adapter-owned
    publisher gives the existing cmd guard a short connection window and emits
    several zeros using wall-clock sleeps.  It never waits on ``/clock``.
    """
    script = """
import time
import rospy
from geometry_msgs.msg import Twist

rospy.init_node('smpcc_sim_h0_zero_twist', anonymous=True, disable_signals=True)
publisher = rospy.Publisher('/cmd_vel', Twist, queue_size=1)
deadline = time.monotonic() + 0.75
while publisher.get_num_connections() == 0 and time.monotonic() < deadline:
    time.sleep(0.05)
zero = Twist()
for _ in range(3):
    publisher.publish(zero)
    time.sleep(0.05)
"""
    result = run_checked(sourced_command(("python3", "-c", script)), environment, timeout_sec, "zero Twist")
    return result.returncode == 0


