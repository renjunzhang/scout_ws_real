def wait_for_development_event(path: Path, record_type: str, case_manifest_hash: str, time_key: str, timeout_sec: float) -> Optional[Mapping[str, Any]]:
    deadline = time.monotonic() + timeout_sec
    while time.monotonic() < deadline:
        if path.is_file():
            return read_development_event(path, record_type, case_manifest_hash, time_key)
        time.sleep(min(0.05, max(0.01, deadline - time.monotonic())))
    if path.is_file():
        return read_development_event(path, record_type, case_manifest_hash, time_key)
    return None


def execution_watcher_command() -> Sequence[str]:
    """Create immutable executed-motion/goal receipts from the live ROS graph."""
    script = r'''
import json
import math
import os
import time
from datetime import datetime, timezone

import rospy
from nav_msgs.msg import Odometry
from std_msgs.msg import String

case_dir = os.environ["SMPCC_H0_CASE_DIR"]
case_manifest_hash = os.environ["SMPCC_CASE_LAUNCH_MANIFEST_SHA256"]
adapter_id = "SMPCC-SIM-H0-RUNTIME-ADAPTER-v2-SOURCE-SEPARATED"
motion_path = os.path.join(case_dir, "h0_first_effective_motion.json")
goal_path = os.path.join(case_dir, "h0_goal_reached_event.json")
linear_threshold = 0.005
angular_threshold = 0.01

def utc_now():
    return datetime.now(timezone.utc).isoformat(timespec="milliseconds")

def write_once(path, payload):
    try:
        with open(path, "x", encoding="utf-8") as stream:
            json.dump(payload, stream, ensure_ascii=False, indent=2, sort_keys=True)
            stream.write("\n")
    except FileExistsError:
        pass

def ros_time(stamp):
    if stamp is not None and not stamp.is_zero():
        return float(stamp.to_sec())
    return float(rospy.Time.now().to_sec())

def odom_callback(message):
    linear = float(message.twist.twist.linear.x)
    angular = float(message.twist.twist.angular.z)
    if not (math.isfinite(linear) and math.isfinite(angular)):
        return
    if abs(linear) < linear_threshold and abs(angular) < angular_threshold:
        return
    observed_ros_time = ros_time(message.header.stamp)
    write_once(motion_path, {
        "record_type": "SMPCC_SIM_DEV_MOTION_EVENT",
        "status": "PASS",
        "adapter_id": adapter_id,
        "case_manifest_hash": case_manifest_hash,
        "observed_topic": "/odom",
        "linear_mps": linear,
        "angular_radps": angular,
        "linear_threshold_mps": linear_threshold,
        "angular_threshold_radps": angular_threshold,
        "first_effective_motion_utc": utc_now(),
        "first_effective_motion_ros_time_sec": observed_ros_time,
        "ros_time_sec": observed_ros_time,
    })

def status_callback(message):
    if message.data != "GOAL_REACHED":
        return
    observed_ros_time = float(rospy.Time.now().to_sec())
    write_once(goal_path, {
        "record_type": "SMPCC_SIM_DEV_GOAL_EVENT",
        "status": "PASS",
        "adapter_id": adapter_id,
        "case_manifest_hash": case_manifest_hash,
        "controller_status": "GOAL_REACHED",
        "observed_topic": "/sim_spmpc/status",
        "first_arrival_utc": utc_now(),
        "first_arrival_ros_time_sec": observed_ros_time,
        "ros_time_sec": observed_ros_time,
    })

rospy.init_node("smpcc_sim_h0_execution_watcher", anonymous=True, disable_signals=True)
rospy.Subscriber("/odom", Odometry, odom_callback, queue_size=50)
rospy.Subscriber("/sim_spmpc/status", String, status_callback, queue_size=50)
rospy.spin()
'''
    return sourced_command(("python3", "-c", script))


