def supervise_motion(environment: Mapping[str, str], case_dir: Path) -> int:
    # The existing attach script starts only path publisher + SPMPC.  It does
    # not create roscore/Gazebo/localization, so the outer runner still owns
    # exactly one fresh environment process group.
    log_root = case_dir / "runtime_logs"
    log_root.mkdir(parents=True, exist_ok=True)
    watcher_log = log_root / "execution_watcher.log"
    with watcher_log.open("w", encoding="utf-8") as stream:
        watcher_child = subprocess.Popen(
            list(execution_watcher_command()),
            env=dict(environment),
            start_new_session=True,
            stdout=stream,
            stderr=subprocess.STDOUT,
        )
        child = subprocess.Popen([str(SPMPC_ATTACH)], env=dict(environment), start_new_session=True)
        handled = {"value": False}

        def stop_handler(signum: int, _frame: Any) -> None:
            if not handled["value"]:
                handled["value"] = True
                zero_published = False
                try:
                    zero_published = publish_zero(environment)
                except AdapterError:
                    zero_published = False
                signal_owned_groups((watcher_child, child))
                motion_stop_receipt(case_dir, child, signal.Signals(signum).name, zero_published)
            raise SystemExit(0)

        old_term = signal.signal(signal.SIGTERM, stop_handler)
        old_int = signal.signal(signal.SIGINT, stop_handler)
        try:
            while True:
                motion_return = child.poll()
                watcher_return = watcher_child.poll()
                if motion_return is not None or watcher_return is not None:
                    signal_owned_groups((watcher_child, child))
                    failed = motion_return if motion_return not in (None, 0) else watcher_return
                    return int(failed if failed not in (None, 0) else 1)
                time.sleep(0.1)
        except BaseException:
            signal_owned_groups((watcher_child, child))
            raise
        finally:
            signal.signal(signal.SIGTERM, old_term)
            signal.signal(signal.SIGINT, old_int)


