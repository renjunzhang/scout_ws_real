def normalize_float32_readback(value: Any, label: str) -> float:
    """Normalize transport-level Float32 noise without accepting non-finite data."""
    require(not isinstance(value, bool), f"{label} must be numeric, not boolean")
    try:
        number = float(value)
    except (TypeError, ValueError) as exc:
        raise AdapterError(f"{label} is not numeric") from exc
    require(math.isfinite(number), f"{label} must be finite")
    normalized = round(number, 6)
    return 0.0 if normalized == 0.0 else normalized


def require_binary_indicator(value: Any, label: str) -> bool:
    normalized = normalize_float32_readback(value, label)
    require(normalized in (0.0, 1.0), f"{label} must be a 0/1 diagnostic indicator")
    return normalized == 1.0


def require_delay_mode(value: Any) -> Tuple[int, str]:
    normalized = normalize_float32_readback(value, "delay_phase_mode_code")
    rounded = int(round(normalized))
    require(abs(normalized - rounded) <= 1e-6, "delay_phase_mode_code must be integral")
    require(rounded in DELAY_MODE_NAMES, f"unknown delay_phase_mode_code: {normalized}")
    return rounded, DELAY_MODE_NAMES[rounded]


def observed_effective_config_from_fields(fields: Mapping[str, Any]) -> Dict[str, Any]:
    """Build the complete, canonical H0 observed-config envelope.

    The envelope deliberately contains every layout field, so an undeclared
    added parameter cannot be invisible to comparison.  ``observer`` is not a
    fabricated controller source: for Bsmooth it is only the safe conclusion
    that an observer is not applicable when the *recorded* slosh-enable bit is
    zero.  A slosh-enabled message records that its source is not verifiable
    from this diagnostic and therefore cannot equal the H0 declaration.
    """
    require(set(fields) == set(H0_EFFECTIVE_CONFIG_LAYOUT_FIELDS), "effective-config fields differ from the H0 readback schema")
    normalized = {
        field: normalize_float32_readback(fields[field], f"effective_config.{field}")
        for field in H0_EFFECTIVE_CONFIG_LAYOUT_FIELDS
    }
    slosh_enabled = require_binary_indicator(normalized["slosh_enable"], "slosh_enable")
    delay_mode_code, delay_mode = require_delay_mode(normalized["delay_phase_mode_code"])
    require_binary_indicator(normalized["delay_require_complete_history"], "delay_require_complete_history")
    observer = (
        {"status": "NOT_APPLICABLE_SLOSH_DISABLED", "slosh_enable": False}
        if not slosh_enabled
        else {"status": "SOURCE_NOT_OBSERVABLE_FROM_EFFECTIVE_CONFIG", "slosh_enable": True}
    )
    return {
        # These fixed envelope markers identify a declared/readback contract;
        # they do not elevate the readback to formal evidence.
        "record_type": "SMPCC_SIM_DEV_H0_DECLARED_READBACK_CONTRACT",
        "config_kind": "H0_DECLARED_READBACK_CONTRACT_NOT_FORMAL",
        "formal": False,
        "development_only": True,
        "fields": normalized,
        "observer": observer,
        "delay": {
            "mode": delay_mode,
            "configured_linear_sec": normalized["delay_linear_sec"],
            "configured_angular_sec": normalized["delay_angular_sec"],
        },
        # Retain the decoded code inside the complete field map while making
        # its interpretation explicit for an audit reader.
        "delay_mode_code": float(delay_mode_code),
    }


def h0_declared_config() -> Dict[str, Any]:
    """Return H0's declared *readback comparison target*, never evidence.

    Its filename and the run spec call it ``declared_config``.  It is kept in
    exactly the same canonical envelope as a rosbag observation solely so a
    post-close audit can require equality without flattening away extra
    fields.  It must never be passed off as an effective-config dump.
    """
    fields = dict(H0_DECLARED_EFFECTIVE_LAYOUT_VALUES)
    require(tuple(fields) == H0_EFFECTIVE_CONFIG_LAYOUT_FIELDS, "H0 declared layout values do not cover the full readback schema")
    return observed_effective_config_from_fields(fields)


def strict_config_diff(declared: Any, observed: Any) -> Dict[str, Dict[str, Any]]:
    """Return every type-sensitive difference, including added parameters."""
    differences: Dict[str, Dict[str, Any]] = {}

    def visit(expected: Any, actual: Any, path: str) -> None:
        if isinstance(expected, Mapping) and isinstance(actual, Mapping):
            for key in sorted(set(expected) | set(actual)):
                child = f"{path}.{key}" if path else str(key)
                if key not in expected:
                    differences[child] = {"declared": "<MISSING>", "observed": actual[key]}
                elif key not in actual:
                    differences[child] = {"declared": expected[key], "observed": "<MISSING>"}
                else:
                    visit(expected[key], actual[key], child)
            return
        if isinstance(expected, list) and isinstance(actual, list):
            max_length = max(len(expected), len(actual))
            for index in range(max_length):
                child = f"{path}[{index}]"
                if index >= len(expected):
                    differences[child] = {"declared": "<MISSING>", "observed": actual[index]}
                elif index >= len(actual):
                    differences[child] = {"declared": expected[index], "observed": "<MISSING>"}
                else:
                    visit(expected[index], actual[index], child)
            return
        if type(expected) is not type(actual) or expected != actual:
            differences[path or "$"] = {"declared": expected, "observed": actual}

    visit(declared, observed, "")
    return differences


def effective_config_field_schema(layout_label: str, size: int, stride: int, data_offset: int) -> Dict[str, Any]:
    labels = [item.strip() for item in layout_label.split(",")]
    require(all(labels), "effective-config layout contains an empty label")
    require(len(set(labels)) == len(labels), "effective-config layout contains duplicate labels")
    require(tuple(labels) == H0_EFFECTIVE_CONFIG_LAYOUT_FIELDS, "effective-config layout label/order differs from the H0 declared schema")
    require(size == len(labels) and stride == len(labels), "effective-config layout size/stride differs from labels")
    require(data_offset == 0, "effective-config layout data_offset must be zero")
    return {
        "topic": EFFECTIVE_CONFIG_TOPIC,
        "message_type": EFFECTIVE_CONFIG_MESSAGE_TYPE,
        "layout_dimension_count": 1,
        "layout_label": layout_label,
        "labels": labels,
        "size": size,
        "stride": stride,
        "data_offset": data_offset,
        "index_by_label": {label: index for index, label in enumerate(labels)},
    }


def parse_effective_config_message(message: Any) -> Dict[str, Any]:
    """Strictly parse one recorded ``Float32MultiArray`` without ROS access."""
    message_type = getattr(message, "_type", EFFECTIVE_CONFIG_MESSAGE_TYPE)
    require(message_type == EFFECTIVE_CONFIG_MESSAGE_TYPE, f"effective-config message type must be {EFFECTIVE_CONFIG_MESSAGE_TYPE}")
    layout = getattr(message, "layout", None)
    dimensions = getattr(layout, "dim", None)
    require(isinstance(dimensions, Sequence) and not isinstance(dimensions, (str, bytes)), "effective-config layout dimensions are missing")
    require(len(dimensions) == 1, "effective-config layout must have exactly one dimension")
    dimension = dimensions[0]
    layout_label = getattr(dimension, "label", None)
    require(isinstance(layout_label, str) and layout_label.strip(), "effective-config layout label is missing")
    try:
        raw_size = getattr(dimension, "size")
        raw_stride = getattr(dimension, "stride")
        raw_data_offset = getattr(layout, "data_offset", 0)
        size = int(raw_size)
        stride = int(raw_stride)
        data_offset = int(raw_data_offset)
    except (TypeError, ValueError) as exc:
        raise AdapterError("effective-config layout size/stride/data_offset is invalid") from exc
    require(size == raw_size and stride == raw_stride and data_offset == raw_data_offset, "effective-config layout size/stride/data_offset must be integral")
    schema = effective_config_field_schema(layout_label, size, stride, data_offset)
    data = getattr(message, "data", None)
    require(isinstance(data, Sequence) and not isinstance(data, (str, bytes)), "effective-config data is missing")
    require(len(data) == len(schema["labels"]), "effective-config data length differs from the declared layout")
    raw_data = []
    normalized_data = []
    for index, value in enumerate(data):
        require(not isinstance(value, bool), f"effective-config data[{index}] must be numeric, not boolean")
        try:
            raw_value = float(value)
        except (TypeError, ValueError) as exc:
            raise AdapterError(f"effective-config data[{index}] is not numeric") from exc
        require(math.isfinite(raw_value), f"effective-config data[{index}] must be finite")
        raw_data.append(raw_value)
        normalized_data.append(normalize_float32_readback(raw_value, f"effective-config data[{index}]"))
    fields = {label: normalized_data[index] for index, label in enumerate(schema["labels"])}
    return {
        "field_schema": schema,
        "field_schema_hash": canonical_hash(schema),
        # Preserve the exact Float32-decoded values for forensic replay.  Only
        # the semantic envelope below is decimal-normalized for a stable
        # declaration comparison.
        "data": raw_data,
        "data_hash": canonical_hash(raw_data),
        "observed_effective_config": observed_effective_config_from_fields(fields),
    }


def require_closed_case_bag(bag_path: Path, case_dir: Path) -> Path:
    """Accept only this case's finalized ``.bag`` file, never an active bag."""
    bag = ensure_within(bag_path, case_dir, "effective-config rosbag")
    require(bag.parent == case_dir, "effective-config rosbag must be directly case-local")
    require(bag.name.endswith(".bag"), "effective-config readback requires a finalized .bag, never .bag.active")
    require(bag.is_file(), f"effective-config rosbag is missing: {bag}")
    require(not Path(str(bag) + ".active").exists(), "effective-config rosbag still has an active recorder artifact")
    return bag


def rosbag_factory() -> Any:
    """Load rosbag only for offline readback; importing it never starts ROS."""
    try:
        import rosbag  # type: ignore
    except ImportError as exc:  # pragma: no cover - depends on sourced ROS environment
        raise AdapterError("rosbag Python module is unavailable for offline effective-config readback") from exc
    return rosbag.Bag


def stamp_seconds(stamp: Any) -> float:
    try:
        value = float(stamp.to_sec()) if hasattr(stamp, "to_sec") else float(stamp)
    except (TypeError, ValueError) as exc:
        raise AdapterError("effective-config rosbag timestamp is invalid") from exc
    require(math.isfinite(value), "effective-config rosbag timestamp must be finite")
    return value


def read_closed_effective_config_bag(bag_path: Path, bag_factory_override: Optional[Any] = None) -> Dict[str, Any]:
    """Read every effective-config message from a finalized rosbag.

    A caller supplies the already-validated case-local path.  The optional
    factory is deliberately injection-friendly for no-ROS unit tests; production
    uses ``rosbag.Bag`` in read-only mode.
    """
    factory = bag_factory_override or rosbag_factory()
    records = []
    schema: Optional[Dict[str, Any]] = None
    schema_hash: Optional[str] = None
    try:
        context = factory(str(bag_path), "r")
    except Exception as exc:  # noqa: BLE001 - rosbag exposes several error classes
        raise AdapterError(f"could not open finalized rosbag for readback: {bag_path}: {exc}") from exc
    try:
        with context as bag:
            try:
                topic_info = bag.get_type_and_topic_info().topics
            except Exception as exc:  # noqa: BLE001 - normalize rosbag implementation errors
                raise AdapterError(f"could not inspect rosbag topic metadata: {exc}") from exc
            require(isinstance(topic_info, Mapping), "rosbag topic metadata is invalid")
            require(EFFECTIVE_CONFIG_TOPIC in topic_info, f"rosbag lacks required topic {EFFECTIVE_CONFIG_TOPIC}")
            type_info = topic_info[EFFECTIVE_CONFIG_TOPIC]
            require(getattr(type_info, "msg_type", None) == EFFECTIVE_CONFIG_MESSAGE_TYPE, f"rosbag {EFFECTIVE_CONFIG_TOPIC} is not {EFFECTIVE_CONFIG_MESSAGE_TYPE}")
            try:
                messages = bag.read_messages(topics=[EFFECTIVE_CONFIG_TOPIC])
                for index, (topic, message, stamp) in enumerate(messages):
                    require(topic == EFFECTIVE_CONFIG_TOPIC, "rosbag reader returned an unexpected effective-config topic")
                    parsed = parse_effective_config_message(message)
                    if schema is None:
                        schema = parsed["field_schema"]
                        schema_hash = parsed["field_schema_hash"]
                    else:
                        require(parsed["field_schema_hash"] == schema_hash, "effective-config schema changed within one rosbag")
                    records.append(
                        {
                            "message_index": index,
                            "ros_time_sec": stamp_seconds(stamp),
                            "data_hash": parsed["data_hash"],
                            "observed_effective_config": parsed["observed_effective_config"],
                            # Keep the selected/latest full raw label/data below;
                            # all records still contribute to this evidence hash.
                            "_data": parsed["data"],
                        }
                    )
            except AdapterError:
                raise
            except Exception as exc:  # noqa: BLE001 - malformed bags must fail closed
                raise AdapterError(f"could not read {EFFECTIVE_CONFIG_TOPIC} from rosbag: {exc}") from exc
    except AdapterError:
        raise
    except Exception as exc:  # noqa: BLE001 - close/read errors are evidence failures
        raise AdapterError(f"rosbag readback failed: {exc}") from exc
    require(records, f"rosbag has no {EFFECTIVE_CONFIG_TOPIC} messages")
    require(schema is not None and schema_hash is not None, "effective-config schema was not captured")
    selected = records[-1]
    observation_chain = [
        {
            "message_index": item["message_index"],
            "ros_time_sec": item["ros_time_sec"],
            "data_hash": item["data_hash"],
            "observed_effective_config_hash": canonical_hash(item["observed_effective_config"]),
        }
        for item in records
    ]
    return {
        "message_count": len(records),
        "first_ros_time_sec": records[0]["ros_time_sec"],
        "last_ros_time_sec": selected["ros_time_sec"],
        "field_schema": schema,
        "field_schema_hash": schema_hash,
        "selected_message": {
            "message_index": selected["message_index"],
            "ros_time_sec": selected["ros_time_sec"],
            "layout_label": schema["layout_label"],
            "data": selected["_data"],
            "data_hash": selected["data_hash"],
        },
        "message_observation_hash": canonical_hash(observation_chain),
        "message_observation_count": len(observation_chain),
        "records": records,
    }


def build_effective_config_readback_report(
    bag_path: Path,
    declared_config: Mapping[str, Any],
    case_manifest_hash: str,
    bag_factory_override: Optional[Any] = None,
) -> Dict[str, Any]:
    """Build a non-formal offline readback report and never mask mismatches."""
    require(len(case_manifest_hash) == 64 and all(char in "0123456789abcdef" for char in case_manifest_hash), "case manifest hash must be lowercase SHA-256")
    require(isinstance(declared_config, Mapping), "declared H0 config must be an object")
    declared = dict(declared_config)
    declared_hash = canonical_hash(declared)
    before_hash = sha256_file(bag_path)
    before_size = bag_path.stat().st_size
    readback = read_closed_effective_config_bag(bag_path, bag_factory_override)
    after_hash = sha256_file(bag_path)
    after_size = bag_path.stat().st_size
    require(before_hash == after_hash and before_size == after_size, "rosbag changed during offline effective-config readback")

    aggregate_diff: Dict[str, Dict[str, Any]] = {}
    mismatch_samples = []
    observed_hashes = []
    for record in readback["records"]:
        observed = record["observed_effective_config"]
        observed_hash = canonical_hash(observed)
        observed_hashes.append(observed_hash)
        difference = strict_config_diff(declared, observed)
        if difference:
            for path, value in difference.items():
                aggregate_diff[f"message[{record['message_index']}].{path}"] = value
            if len(mismatch_samples) < 8:
                mismatch_samples.append(
                    {
                        "message_index": record["message_index"],
                        "ros_time_sec": record["ros_time_sec"],
                        "diff": difference,
                    }
                )
    selected_observed = readback["records"][-1]["observed_effective_config"]
    selected_hash = canonical_hash(selected_observed)
    return {
        "record_type": EFFECTIVE_CONFIG_READBACK_RECORD_TYPE,
        "status": "PASS" if not aggregate_diff else "FAIL",
        "formal": False,
        "development_only": True,
        "evidence_class": DEVELOPMENT_EVIDENCE_CLASS,
        "source": EFFECTIVE_CONFIG_READBACK_SOURCE,
        "source_topic": EFFECTIVE_CONFIG_TOPIC,
        "source_message_type": EFFECTIVE_CONFIG_MESSAGE_TYPE,
        "case_manifest_hash": case_manifest_hash,
        "bag_path": str(bag_path),
        "bag_sha256": before_hash,
        "bag_size_bytes": before_size,
        "field_schema": readback["field_schema"],
        "field_schema_hash": readback["field_schema_hash"],
        "message_count": readback["message_count"],
        "first_ros_time_sec": readback["first_ros_time_sec"],
        "last_ros_time_sec": readback["last_ros_time_sec"],
        "selected_message": readback["selected_message"],
        "message_observation_hash": readback["message_observation_hash"],
        "message_observation_count": readback["message_observation_count"],
        "unique_observed_effective_config_hashes": sorted(set(observed_hashes)),
        "declared_config_hash": declared_hash,
        "observed_effective_config": selected_observed,
        "observed_effective_config_hash": selected_hash,
        "declared_vs_observed_diff": aggregate_diff,
        "mismatch_message_count": sum(1 for record in readback["records"] if strict_config_diff(declared, record["observed_effective_config"])),
        "mismatch_message_samples": mismatch_samples,
        "required_audit_coverage": {
            "weights_and_v_ref": ["w_control", "w_smooth", "w_alpha", "w_du_a", "w_du_vs", "w_slosh", "v_ref"],
            "observer": "derived only from recorded slosh_enable; no source is fabricated",
            "delay": ["delay_phase_mode_code", "delay_linear_sec", "delay_angular_sec"],
            "full_layout_required": True,
        },
        "physical_primary_eligible": False,
        "not_formal_or_h1_l1": True,
    }


def case_dir_for(row: Mapping[str, Any], attempt_number: int = 1) -> Path:
    require(attempt_number == 1, "H0 adapter supports only the initial development attempt r01")
    try:
        position = int(row["order_position"])
    except (KeyError, TypeError, ValueError) as exc:
        raise AdapterError("H0 row has no valid order_position") from exc
    return Path(str(row["stage"])) / str(row["block_id"]) / f"p{position:02d}_{row['condition_id']}" / f"r{attempt_number:02d}"


def require_h0_row(row: Mapping[str, Any], label: str) -> None:
    require(row.get("formal") is False, f"{label} must be non-formal")
    require(row.get("evidence_class") == DEVELOPMENT_EVIDENCE_CLASS, f"{label} has wrong development evidence class")
    require(row.get("stage") == H0_STAGE, f"{label} must use {H0_STAGE}")
    require(str(row.get("planned_row_id", "")).startswith(H0_ROW_PREFIX), f"{label} is not an H0 row")
    require(row.get("condition_id") == "Bsmooth", f"{label} may only use Bsmooth")
    require(row.get("path_id") == "H0", f"{label} must use H0, never H1/L1")
    require(row.get("method_backend") == "online_mpcc", f"{label} has wrong backend")
    require("w5_s10" not in canonical_bytes(dict(row)).decode("utf-8").lower(), f"{label} must not contain W5_S10")


def readback_case_context(args: argparse.Namespace) -> Tuple[Mapping[str, Any], Path, str]:
    """Bind an offline readback to one already-created H0 case manifest."""
    case_dir = ensure_within(Path(args.case_dir), SIM_ROOT, "H0 readback case directory")
    require(case_dir.is_dir(), f"H0 readback case directory is missing: {case_dir}")
    manifest_path = ensure_within(Path(args.case_manifest), case_dir, "H0 readback case manifest")
    require(manifest_path.parent == case_dir, "H0 readback case manifest must be directly case-local")
    require(manifest_path.is_file(), f"H0 readback case manifest is missing: {manifest_path}")
    manifest = read_json(manifest_path, "H0 readback case manifest")
    require(manifest.get("formal") is False, "H0 effective-config readback refuses a formal case")
    planned_row_id = str(manifest.get("planned_row_id", ""))
    attempt_id = str(manifest.get("attempt_id", ""))
    require(planned_row_id.startswith(H0_ROW_PREFIX) and attempt_id.startswith(H0_ROW_PREFIX), "H0 effective-config readback refuses non-H0 rows")
    expected_hash = args.case_manifest_sha256 or os.environ.get("SMPCC_CASE_LAUNCH_MANIFEST_SHA256", "")
    require(isinstance(expected_hash, str) and expected_hash, "H0 effective-config readback requires --case-manifest-sha256 or SMPCC_CASE_LAUNCH_MANIFEST_SHA256")
    actual_hash = sha256_file(manifest_path)
    require(actual_hash == expected_hash, "H0 readback case-manifest hash does not match its binding")
    return manifest, case_dir, actual_hash


def runtime_context(args: argparse.Namespace) -> Tuple[Mapping[str, Any], Path, str, str]:
    manifest_value = args.case_manifest or os.environ.get("SMPCC_CASE_LAUNCH_MANIFEST_PATH", "")
    require(manifest_value, "H0 runtime requires SMPCC_CASE_LAUNCH_MANIFEST_PATH or --case-manifest")
    manifest_path = ensure_within(Path(manifest_value), SIM_ROOT, "case launch manifest")
    manifest = read_json(manifest_path, "case launch manifest")
    require(manifest.get("formal") is False, "H0 adapter refuses formal runtime manifests")
    planned_row_id = str(manifest.get("planned_row_id", ""))
    attempt_id = str(manifest.get("attempt_id", ""))
    require(planned_row_id.startswith(H0_ROW_PREFIX) and attempt_id.startswith(H0_ROW_PREFIX), "H0 adapter refuses non-H0 planned rows")
    expected_manifest_hash = os.environ.get("SMPCC_CASE_LAUNCH_MANIFEST_SHA256", "")
    require(expected_manifest_hash, "H0 runtime requires runner case-manifest hash binding")
    require(sha256_file(manifest_path) == expected_manifest_hash, "runner case-manifest hash does not match H0 manifest")
    seed_path_value = os.environ.get("SMPCC_SEED_BUNDLE_PATH", "")
    seed_hash = os.environ.get("SMPCC_SEED_BUNDLE_SHA256", "")
    require(seed_path_value and seed_hash, "H0 runtime requires runner seed-bundle binding")
    seed_path = ensure_within(Path(seed_path_value), SIM_ROOT, "runtime seed bundle")
    require(seed_path.is_file(), "runtime seed bundle is missing")
    validate_h0_seed_bundle(read_json(seed_path, "runtime seed bundle"), seed_hash)
    require(manifest.get("seed_bundle_path") == str(seed_path), "case manifest seed path differs from runtime seed")
    require(manifest.get("seed_bundle_hash") == seed_hash, "case manifest seed hash differs from runtime seed")
    case_dir = ensure_within(Path(args.case_dir), SIM_ROOT, "H0 case directory")
    require(case_dir == manifest_path.parent.resolve(), "H0 case directory must be the case-manifest parent")
    ros_uri, gazebo_uri = resolve_runtime_uris(args)
    require(manifest.get("ros_master_uri") == ros_uri, "H0 ROS URI differs from case manifest")
    require(manifest.get("gazebo_master_uri") == gazebo_uri, "H0 Gazebo URI differs from case manifest")
    return manifest, case_dir, ros_uri, gazebo_uri


def runtime_development_liquid_plant(
    args: argparse.Namespace, manifest: Mapping[str, Any]
) -> Optional[Dict[str, Any]]:
    """Bind a runtime opt-in exactly to the outer runner's case manifest."""
    selected = resolve_development_liquid_plant(args)
    declared = manifest.get("liquid_plant_capability")
    if selected is None:
        # Older default-H0 case manifests did not carry this field.  They are
        # still valid only as no-plant H0 cases; a manifest that declares an
        # independent plant cannot be launched without the explicit CLI flag.
        if isinstance(declared, Mapping):
            require(declared.get("independent_plant") is not True, "case manifest declares a development liquid plant but this runtime command did not opt in")
        else:
            require(declared is None, "case manifest liquid-plant declaration is malformed")
        return None
    require(isinstance(declared, Mapping), "case manifest lacks the selected development liquid-plant capability")
    require(canonical_hash(dict(declared)) == canonical_hash(selected), "selected development liquid-plant capability differs from case manifest")
    require(declared.get("formal") is False and declared.get("development_only") is True, "case manifest liquid plant is not development-only")
    require(declared.get("fidelity_validation_status") == "UNVALIDATED", "H0 runtime refuses a plant not explicitly marked UNVALIDATED")
    require(declared.get("physical_primary_eligible") is False, "H0 runtime refuses a physical-primary plant declaration")
    return selected


def runtime_development_firewall(
    manifest: Mapping[str, Any], case_dir: Path, liquid_plant: Optional[Mapping[str, Any]]
) -> Optional[Dict[str, Any]]:
    """Bind the opt-in subscriber-firewall contract to the case manifest.

    Default H0 deliberately has no live H_plant and therefore no additional
    controller-side firewall requirement.  Conversely, an opted-in plant may
    not run without this contract: that prevents a future convenience flag
    from silently opening a controller truth input.
    """
    declared = manifest.get("development_firewall")
    if liquid_plant is None:
        require(declared is None, "default H0 runtime refuses an unexpected development firewall contract")
        return None
    require(isinstance(declared, Mapping), "development liquid-plant H0 case lacks subscriber-firewall contract")
    validated = validate_development_firewall_contract(declared, case_dir)
    require(
        validated.get("requires_development_liquid_plant") is True,
        "development firewall does not bind the selected liquid plant",
    )
    return validated


def runtime_environment(
    ros_uri: str,
    gazebo_uri: str,
    case_dir: Path,
    *,
    visualize: bool = False,
    liquid_plant: Optional[Mapping[str, Any]] = None,
) -> Dict[str, str]:
    """Build the H0 runtime environment.

    Normal H0 evidence collection stays headless.  ``visualize`` is an
    explicit development-only opt-in that exposes Gazebo and the tracking RViz
    on the current display; it is deliberately carried in the generated run
    spec so a visual replay cannot silently look like the normal headless
    smoke.

    The simulation-owned environment launch creates Gazebo headlessly.  A
    roslaunch-owned GUI would make
    the GUI's ownership ambiguous after the launcher tears down.  Keep that
    launch argument false in *both* modes.  In visual mode
    :func:`supervise_environment` starts one direct, adapter-owned ``gzclient``
    child after the fresh Gazebo master is reachable and includes that exact
    process group in its bounded cleanup set.
    """
    environment = dict(os.environ)
    # The adapter owns an isolated, loopback-only master.  Do not let a
    # workstation shell's real-robot ROS identity leak into auxiliary
    # publishers (especially the bounded zero-Twist publisher during tail
    # capture).  ``ROS_HOSTNAME`` takes precedence over ``ROS_IP`` in roscpp
    # and rospy, so remove it explicitly rather than merely overwriting IP.
    environment.pop("ROS_HOSTNAME", None)
    environment.update(
        {
            "ROS_MASTER_URI": ros_uri,
            "GAZEBO_MASTER_URI": gazebo_uri,
            "ROS_IP": "127.0.0.1",
            "ROS_NAMESPACE": "/",
            "SMPCC_SIM_ROS_PACKAGE_PATH": SIM_ROS_PACKAGE_PATH,
            "SCOUT_PROXY_FULL_ROS_MASTER_URI": ros_uri,
            "SCOUT_PROXY_FULL_GAZEBO_MASTER_URI": gazebo_uri,
            "MAP_FILE": str(MAP_FILE),
            "WORLD_NAME": str(WORLD_FILE),
            "SPAWN_X": str(P2["spawn"]["x"]),
            "SPAWN_Y": str(P2["spawn"]["y"]),
            "SPAWN_Z": str(P2["spawn"]["z"]),
            "SPAWN_YAW": str(P2["spawn"]["yaw"]),
            "GOAL_X": str(P2["goal"]["x"]),
            "GOAL_Y": str(P2["goal"]["y"]),
            "GOAL_YAW": str(P2["goal"]["yaw"]),
            "PATH_TEMPLATE": "s_curve",
            "PATH_START_HEADING": "current",
            "PATH_AMPLITUDE_RATIO": str(P2["path_template"]["amplitude_ratio"]),
            "PATH_MIN_AMPLITUDE": str(P2["path_template"]["min_amplitude"]),
            "PATH_MAX_AMPLITUDE": str(P2["path_template"]["max_amplitude"]),
            "PATH_SIDE": str(P2["path_template"]["side"]),
            "PATH_SMOOTH_ITERATIONS": str(P2["path_template"]["smooth_iterations"]),
            "PLANNER_VARIANT": "B_smooth",
            "SOLVER_BACKEND": "continuous_mpcc_acados",
            "ALPHA_MAX": str(P2["limits"]["alpha_max_radps2"]),
            "MAX_ANGULAR_ACCEL": str(P2["limits"]["alpha_max_radps2"]),
            "W_SLOSH": "0.0",
            "V_REF": "0.25",
            "W_ALPHA": "1.0",
            "W_DU_A": "1.0",
            "W_DU_VS": "1.0",
            "CMD_VEL_TOPIC": "/cmd_vel",
            "COSTMAP_TOPIC": "/map",
            "REFERENCE_TARGET_FRAME": "odom",
            "PUBLISH_CMD_VEL": "true",
            "DELAY_PHASE_MODE": "off",
            "DELAY_PHASE_LINEAR_DELAY_SEC": "-1.0",
            "DELAY_PHASE_ANGULAR_DELAY_SEC": "-1.0",
            "USE_RVIZ": "true" if visualize else "false",
            # Never let the environment roslaunch create gzclient.  The explicit
            # visual child is selected separately below so it has an adapter
            # Popen handle and cannot be mistaken for an old GUI process.
            "GAZEBO_GUI": "false",
            "TRACKING_RVIZ": "true" if visualize else "false",
            "LOCALIZATION_RVIZ": "false",
            "HEADLESS": "false" if visualize else "true",
            "SMPCC_H0_OWNED_GZCLIENT": "true" if visualize else "false",
            "REQUIRE_TRACKING_RVIZ": "false",
            "SMPCC_H0_CASE_DIR": str(case_dir),
            # Startup-only admission allowance for the restored Cartographer
            # map->base transform.  It is distinct from, and never extends,
            # the 60 s effective-motion deadline enforced by the outer row
            # runner.
            "TF_TIMEOUT": "75",
            "ROS_LOG_DIR": str(case_dir / "ros_logs"),
            "LOG_DIR": str(case_dir / "runtime_logs"),
        }
    )
    if liquid_plant is not None:
        require(liquid_plant.get("formal") is False and liquid_plant.get("development_only") is True, "H0 runtime environment refuses a non-development liquid plant")
        existing_pythonpath = environment.get("PYTHONPATH", "")
        plant_pythonpath = str(LIQUID_PLANT_PYTHON_ROOT.resolve())
        environment["PYTHONPATH"] = (
            plant_pythonpath
            if not existing_pythonpath
            else plant_pythonpath + os.pathsep + existing_pythonpath
        )
        environment["SMPCC_H0_DEVELOPMENT_LIQUID_PLANT"] = "true"
        environment["SMPCC_H0_DEVELOPMENT_LIQUID_PLANT_CONFIG"] = str(liquid_plant["plant_parameter_path"])
    return environment


def visualization_contract(visualize: bool) -> Dict[str, Any]:
    """Return the immutable ownership declaration for an H0 visual replay."""
    return {
        "requested": bool(visualize),
        "mode": "gazebo_gui_and_tracking_rviz" if visualize else "headless",
        "formal": False,
        # The environment launcher always receives ``GAZEBO_GUI=false``.  A
        # requested GUI is instead one direct child that this adapter owns.
        "roslaunch_gazebo_gui": False,
        "gazebo_gui_owner": "adapter_direct_gzclient_child" if visualize else None,
    }


def write_runtime_receipt(
    case_dir: Path,
    manifest: Mapping[str, Any],
    ros_uri: str,
    gazebo_uri: str,
    liquid_plant: Optional[Mapping[str, Any]] = None,
    *,
    visualize: bool = False,
) -> None:
    receipt = h0_descriptor(liquid_plant)
    receipt.update(
        {
            "case_manifest_path": str(case_dir / "case_launch_manifest.json"),
            "case_manifest_hash": sha256_file(case_dir / "case_launch_manifest.json"),
            "planned_row_id": manifest["planned_row_id"],
            "attempt_id": manifest["attempt_id"],
            "ros_master_uri": ros_uri,
            "gazebo_master_uri": gazebo_uri,
            "adapter_source_hash": sha256_file(Path(__file__).resolve()),
            "liquid_plant_capability": dict(liquid_plant) if liquid_plant is not None else None,
            "development_firewall": manifest.get("development_firewall"),
            "visualization": visualization_contract(visualize),
        }
    )
    # Keep a human-facing name as well as the adapter-contract name.  Both are
    # tiny, identical, immutable development context records under the case.
    for name in ("development_run_context.json", "h0_runtime_adapter_contract.json"):
        path = case_dir / name
        write_json_once_or_same(path, receipt)
        os.chmod(path, 0o444)


def command_launch(args: argparse.Namespace) -> int:
    manifest, case_dir, ros_uri, gazebo_uri = runtime_context(args)
    liquid_plant = runtime_development_liquid_plant(args, manifest)
    runtime_development_firewall(manifest, case_dir, liquid_plant)
    static_assets()
    write_runtime_receipt(
        case_dir,
        manifest,
        ros_uri,
        gazebo_uri,
        liquid_plant,
        visualize=bool(args.visualize),
    )
    environment = runtime_environment(
        ros_uri,
        gazebo_uri,
        case_dir,
        visualize=bool(args.visualize),
        liquid_plant=liquid_plant,
    )
    environment.update(
        {
            "START_PROXY": "true",
            "START_LOCALIZATION": "true",
            "START_PATH_PUBLISHER": "false",
            "START_SPMPC": "false",
        }
    )
    return supervise_environment(environment, case_dir, ros_uri, liquid_plant)


def sourced_command(command: Sequence[str]) -> Sequence[str]:
    """Return an isolated non-login ROS command argv.

    The separately built simulation ``devel/setup.bash`` is needed to find
    the fork's executable.  It is deliberately below ``SIM_ROOT`` rather
    than the shared workspace.  Re-apply a narrow package allowlist and
    isolated prefix afterwards so utility nodes such as the recorder and
    zero-Twist publisher cannot resolve a real-robot controller by name.  A
    non-login shell also avoids a user's shell profile reintroducing a
    physical ROS identity.
    """
    require(ROS_SETUP.is_file() and SIM_SETUP.is_file(), "ROS/isolated-simulation setup files are unavailable")
    quoted = shlex.join(list(command))
    script = (
        "set -euo pipefail; "
        "export ROS_DISTRO=\"${ROS_DISTRO:-}\"; "
        "source /opt/ros/noetic/setup.bash; "
        f"source {shlex.quote(str(SIM_SETUP))}; "
        "export ROS_IP=127.0.0.1; export ROS_NAMESPACE=/; unset ROS_HOSTNAME; "
        f"export CMAKE_PREFIX_PATH={shlex.quote(str(SIM_DEVEL))}:/opt/ros/noetic; "
        f"export PATH={shlex.quote(str(SIM_DEVEL / 'bin'))}:/opt/ros/noetic/bin:${{PATH}}; "
        f"export LD_LIBRARY_PATH={shlex.quote(str(SIM_DEVEL / 'lib'))}:/opt/ros/noetic/lib; "
        f"export PYTHONPATH={shlex.quote(str(SIM_DEVEL / 'lib/python3/dist-packages'))}:/opt/ros/noetic/lib/python3/dist-packages; "
        f"export ROS_PACKAGE_PATH={shlex.quote(SIM_ROS_PACKAGE_PATH)}; "
        "exec " + quoted
    )
    return ("/bin/bash", "-c", script)


def run_checked(command: Sequence[str], environment: Mapping[str, str], timeout_sec: float, label: str) -> subprocess.CompletedProcess[str]:
    try:
        return subprocess.run(
            list(command),
            env=dict(environment),
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            timeout=timeout_sec,
            check=False,
        )
    except subprocess.TimeoutExpired as exc:
        raise AdapterError(f"{label} timed out after {timeout_sec:g}s") from exc


def wait_one_topic(topic: str, environment: Mapping[str, str], timeout_sec: float) -> None:
    result = run_checked(sourced_command(("rostopic", "echo", "-n", "1", topic)), environment, timeout_sec, f"topic {topic}")
    require(result.returncode == 0, f"readiness topic unavailable: {topic}: {result.stdout[-500:]}")


def wait_map_tf(environment: Mapping[str, str], timeout_sec: float) -> None:
    """Observe one map->base_link sample, then terminate only this probe.

    ``tf_echo`` is intentionally long-lived.  A shell pipeline ending in
    ``grep -m1`` can still wait for its upstream process (or return 124 after
    an enclosing timeout) even after it has printed a valid translation.  Read
    the probe directly so a sample is authoritative and its own process group
    is stopped immediately afterwards.
    """
    process: Optional[subprocess.Popen[str]] = None
    output: list[str] = []
    deadline = time.monotonic() + timeout_sec
    try:
        process = subprocess.Popen(
            list(sourced_command(("rosrun", "tf", "tf_echo", "map", "base_link"))),
            env=dict(environment),
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            start_new_session=True,
            bufsize=1,
        )
        while time.monotonic() < deadline:
            assert process.stdout is not None
            remaining = max(0.01, deadline - time.monotonic())
            readable, _, _ = select.select([process.stdout], [], [], min(0.25, remaining))
            if readable:
                line = process.stdout.readline()
                if line:
                    output.append(line)
                    if "Translation:" in line:
                        return
            if process.poll() is not None:
                break
    finally:
        if process is not None:
            signal_owned_group(process, signal.SIGTERM, 2.0)
    require(False, "readiness TF map->base_link unavailable: " + "".join(output)[-500:])


def wait_for_development_firewall_roles(
    ros_uri: str, contract: Mapping[str, Any], timeout_sec: float
) -> None:
    """Wait for the pre-armed H0 controller chain without subscribing to ROS.

    The optional plant mode pre-arms the controller while the path publisher
    remains absent, so all four role labels can be audited before recorder
    start and motion release.  This polling uses only ROS-master system state.
    """
    deadline = time.monotonic() + timeout_sec
    last_error = ""
    while time.monotonic() < deadline:
        try:
            report = evaluate_development_firewall(
                read_ros_master_subscriber_graph(ros_uri), contract
            )
            if not report["missing_controller_nodes"]:
                return
            last_error = "missing controller nodes: " + ", ".join(report["missing_controller_nodes"])
        except AdapterError as exc:
            last_error = str(exc)
        time.sleep(min(0.10, max(0.01, deadline - time.monotonic())))
    raise AdapterError(
        "H0 development firewall role readiness timed out: " + (last_error or "no graph")
    )


def command_ready(args: argparse.Namespace) -> int:
    manifest, case_dir, ros_uri, gazebo_uri = runtime_context(args)
    liquid_plant = runtime_development_liquid_plant(args, manifest)
    firewall = runtime_development_firewall(manifest, case_dir, liquid_plant)
    environment = runtime_environment(ros_uri, gazebo_uri, case_dir, liquid_plant=liquid_plant)
    timeout_sec = float(args.timeout_sec)
    # This is pre-motion infrastructure admission, not the 60 s effective
    # trajectory deadline.  It must cover the environment launcher's 75 s
    # map->base_link recovery ceiling plus a bounded observation margin.
    require(0.1 <= timeout_sec <= 120.0 and math.isfinite(timeout_sec), "ready timeout must be within (0, 120]")
    # This is one readiness budget, not five independent 60-second waits.
    # The outer single-row runner must therefore be given a command timeout
    # slightly larger than this budget.  Cartographer's map->base_link can
    # legitimately be the last prerequisite after the four ROS topics exist.
    deadline = time.monotonic() + timeout_sec

    def remaining(label: str) -> float:
        value = deadline - time.monotonic()
        require(value > 0.05, f"H0 readiness budget exhausted before {label}")
        return value

    # H0 is intentionally odometry-observer-only: the simulation controller
    # has imu_shadow disabled, so an optional Gazebo IMU must neither gate
    # readiness nor masquerade as a frozen information source.
    ready_topics = ("/odom", "/scan_front", "/map", "/slosh/height")
    if liquid_plant is not None:
        ready_topics += LIQUID_PLANT_RECORDED_TOPICS
    for topic in ready_topics:
        wait_one_topic(topic, environment, remaining(topic))
    wait_map_tf(environment, remaining("map->base_link"))
    if firewall is not None:
        wait_for_development_firewall_roles(ros_uri, firewall, remaining("development firewall roles"))
    print(
        json.dumps(
            {
                "status": "PASS",
                "stage": H0_STAGE,
                "ready_topics": list(ready_topics),
                "tf": "map->base_link",
                "H_proxy": "/slosh/height",
                "H_modal": "/sim_spmpc/slosh_height",
                "H_plant": None
                if liquid_plant is None
                else {
                    "topic": liquid_plant["truth_topic"],
                    "fidelity_validation_status": "UNVALIDATED",
                    "physical_primary_eligible": False,
                },
                "development_firewall": None
                if firewall is None
                else {
                    "enabled": True,
                    "contract_hash": firewall["contract_hash"],
                    "controller_nodes": firewall["controller_nodes"],
                    "physical_primary_eligible": False,
                },
                "ros_master_uri": ros_uri,
                "gazebo_master_uri": gazebo_uri,
            },
            sort_keys=True,
        )
    )
    return 0


def command_firewall_snapshot(args: argparse.Namespace) -> int:
    """Write one live, immutable controller subscriber-firewall snapshot.

    This command is intentionally unavailable to default H0.  It is called by
    the outer single-row runner at ready, pre-motion and postflight while the
    fresh master is still alive; it never starts ROS/Gazebo and never creates a
    ROS subscriber of its own.
    """
    manifest, case_dir, ros_uri, _gazebo_uri = runtime_context(args)
    liquid_plant = runtime_development_liquid_plant(args, manifest)
    firewall = runtime_development_firewall(manifest, case_dir, liquid_plant)
    require(liquid_plant is not None and firewall is not None, "H0 firewall snapshot requires --with-development-liquid-plant")
    checkpoint = str(args.checkpoint)
    require(
        checkpoint in H0_DEVELOPMENT_FIREWALL_CHECKPOINTS,
        "H0 firewall snapshot checkpoint is invalid",
    )
    output = development_firewall_snapshot_path(case_dir, checkpoint)
    require(not output.exists(), f"H0 firewall snapshot already exists: {output}")
    case_manifest_hash = os.environ["SMPCC_CASE_LAUNCH_MANIFEST_SHA256"]
    try:
        graph = read_ros_master_subscriber_graph(ros_uri)
        snapshot = build_development_firewall_snapshot(
            checkpoint, case_dir, case_manifest_hash, firewall, graph=graph
        )
    except AdapterError as exc:
        # Preserve an immutable failing artifact where possible.  The runner
        # subsequently rejects it, so absence cannot be mistaken for PASS.
        snapshot = build_development_firewall_snapshot(
            checkpoint,
            case_dir,
            case_manifest_hash,
            firewall,
            graph={"subscriptions": {}},
            capture_error=str(exc),
        )
    write_json_new(output, snapshot)
    print(
        json.dumps(
            {
                "status": snapshot["status"],
                "formal": False,
                "development_only": True,
                "physical_primary_eligible": False,
                "checkpoint": checkpoint,
                "output": str(output),
                "case_manifest_hash": case_manifest_hash,
                "firewall_contract_hash": firewall["contract_hash"],
                "missing_controller_nodes": snapshot["missing_controller_nodes"],
                "forbidden_controller_subscribers": snapshot[
                    "forbidden_controller_subscribers"
                ],
            },
            ensure_ascii=False,
            sort_keys=True,
        )
    )
    return 0 if snapshot["status"] == "PASS" else 2


def active_bag_base(artifact: Path) -> Path:
    require(artifact.name.endswith(".bag.active"), "H0 recorder artifact must end with .bag.active")
    return artifact.with_name(artifact.name[: -len(".bag.active")])


