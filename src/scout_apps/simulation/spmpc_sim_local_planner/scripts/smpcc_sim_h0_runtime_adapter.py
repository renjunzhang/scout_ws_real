def canonical_subscriber_graph(graph: Mapping[str, Any]) -> Dict[str, Any]:
    """Canonicalize the read-only ROS-master subscriber half of system state."""
    subscriptions = graph.get("subscriptions")
    require(isinstance(subscriptions, Mapping), "H0 firewall graph subscriptions must be an object")
    canonical: Dict[str, list[str]] = {}
    for topic, nodes in sorted(subscriptions.items()):
        require(isinstance(topic, str) and topic.startswith("/"), "H0 firewall graph topic must be absolute")
        require(
            isinstance(nodes, list)
            and all(isinstance(node, str) and node.startswith("/") for node in nodes),
            f"H0 firewall graph subscribers for {topic} must be absolute node names",
        )
        canonical[str(topic)] = sorted(set(nodes))
    return {"subscriptions": canonical}


def read_ros_master_subscriber_graph(ros_uri: str) -> Dict[str, Any]:
    """Read only ROS master system state; it never subscribes or mutates ROS."""
    try:
        proxy = xmlrpc.client.ServerProxy(ros_uri.rstrip("/"), allow_none=True)
        code, _message, state = proxy.getSystemState("/smpcc_sim_h0_firewall_snapshot")
        require(code == 1 and isinstance(state, list) and len(state) == 3, "ROS master did not return system state")
        subscriptions = state[1]
        require(isinstance(subscriptions, list), "ROS master subscriber state is malformed")
        return canonical_subscriber_graph({"subscriptions": dict(subscriptions)})
    except (OSError, xmlrpc.client.Error, TypeError, ValueError, AdapterError) as exc:
        raise AdapterError(f"cannot read H0 live ROS subscriber graph {ros_uri}: {exc}") from exc


def evaluate_development_firewall(
    graph: Mapping[str, Any], contract: Mapping[str, Any]
) -> Dict[str, Any]:
    """Evaluate the H0 controller-side information firewall.

    A bag recorder may correctly subscribe to ``/sim_truth/*`` after it starts;
    it is not part of the controller chain.  The rejection set is therefore
    every explicitly identified controller/planner/tracker/cmd-gate role,
    including a fused role node.  The complete set of truth-topic subscribers
    is retained in the snapshot for audit rather than silently discarded.
    """
    normal = canonical_subscriber_graph(graph)
    roles = contract["node_roles"]
    assert isinstance(roles, Mapping)  # established by contract validation
    protected_nodes = set(contract["controller_nodes"])
    seen_nodes = {
        node for nodes in normal["subscriptions"].values() for node in nodes
    }
    missing = sorted(protected_nodes - seen_nodes)
    truth_subscribers = []
    forbidden = []
    prefixes = tuple(contract["forbidden_topic_prefixes"])
    for topic, nodes in normal["subscriptions"].items():
        if topic.startswith(prefixes):
            truth_subscribers.append({"topic": topic, "subscribers": list(nodes)})
            for role, node in sorted(roles.items()):
                if node in nodes:
                    forbidden.append({"role": role, "node": node, "topic": topic})
    return {
        "status": "PASS" if not missing and not forbidden else "FAIL",
        "node_roles": dict(roles),
        "controller_nodes": sorted(protected_nodes),
        "missing_controller_nodes": missing,
        "forbidden_controller_subscribers": forbidden,
        "all_sim_truth_subscribers": truth_subscribers,
        "graph": normal,
        "graph_hash": canonical_hash(normal),
    }


def build_development_firewall_snapshot(
    checkpoint: str,
    case_dir: Path,
    case_manifest_hash: str,
    contract: Mapping[str, Any],
    graph: Optional[Mapping[str, Any]] = None,
    capture_error: Optional[str] = None,
) -> Dict[str, Any]:
    """Build immutable, non-primary evidence for one lifecycle checkpoint."""
    require(checkpoint in H0_DEVELOPMENT_FIREWALL_CHECKPOINTS, "invalid H0 firewall checkpoint")
    validated = validate_development_firewall_contract(contract, case_dir)
    require(isinstance(case_manifest_hash, str) and len(case_manifest_hash) == 64, "H0 firewall requires a case-manifest SHA-256")
    if graph is None:
        graph = {"subscriptions": {}}
    evaluation = evaluate_development_firewall(graph, validated)
    if capture_error is not None:
        evaluation["status"] = "FAIL"
        evaluation["capture_error"] = capture_error
    snapshot_path = development_firewall_snapshot_path(case_dir, checkpoint)
    return {
        "schema_version": 1,
        "record_type": H0_DEVELOPMENT_FIREWALL_RECORD_TYPE,
        "snapshot_id": f"{H0_DEVELOPMENT_FIREWALL_ID}:{checkpoint}",
        "status": evaluation["status"],
        "development_only": True,
        "formal": False,
        "physical_primary_eligible": False,
        "evidence_class": DEVELOPMENT_EVIDENCE_CLASS,
        "semantic": "controller-side subscriber firewall for UNVALIDATED H0 development plant; not physical-primary evidence",
        "checkpoint": checkpoint,
        "case_dir": str(ensure_within(case_dir, SIM_ROOT, "H0 firewall case directory")),
        "snapshot_path": str(snapshot_path),
        "case_manifest_hash": case_manifest_hash,
        "firewall_contract_hash": validated["contract_hash"],
        "liquid_truth_semantic": "H_plant development surrogate only; H_proxy/H_modal remain nonprimary",
        "captured_utc": datetime.now(timezone.utc).isoformat(timespec="milliseconds"),
        **evaluation,
    }


def validate_development_firewall_snapshot(
    snapshot: Mapping[str, Any],
    checkpoint: str,
    case_dir: Path,
    case_manifest_hash: str,
    contract: Mapping[str, Any],
) -> Dict[str, Any]:
    """Recompute the pass/fail result before a runner admits a snapshot."""
    validated = validate_development_firewall_contract(contract, case_dir)
    require(snapshot.get("record_type") == H0_DEVELOPMENT_FIREWALL_RECORD_TYPE, "H0 firewall snapshot record type mismatch")
    require(snapshot.get("checkpoint") == checkpoint, "H0 firewall snapshot checkpoint mismatch")
    require(snapshot.get("status") == "PASS", "H0 firewall snapshot is not PASS")
    require(snapshot.get("development_only") is True and snapshot.get("formal") is False, "H0 firewall snapshot lost development/non-formal status")
    require(snapshot.get("physical_primary_eligible") is False, "H0 firewall snapshot became physical-primary")
    require(snapshot.get("case_manifest_hash") == case_manifest_hash, "H0 firewall snapshot belongs to another case manifest")
    require(snapshot.get("firewall_contract_hash") == validated["contract_hash"], "H0 firewall snapshot contract hash mismatch")
    require(snapshot.get("snapshot_path") == str(development_firewall_snapshot_path(case_dir, checkpoint)), "H0 firewall snapshot path mismatch")
    evaluation = evaluate_development_firewall(
        snapshot.get("graph") if isinstance(snapshot.get("graph"), Mapping) else {},
        validated,
    )
    require(evaluation["status"] == "PASS", "H0 firewall snapshot graph fails controller subscriber firewall")
    for key in (
        "node_roles",
        "controller_nodes",
        "missing_controller_nodes",
        "forbidden_controller_subscribers",
        "all_sim_truth_subscribers",
        "graph",
        "graph_hash",
    ):
        require(snapshot.get(key) == evaluation.get(key), f"H0 firewall snapshot {key} mismatch")
    return dict(snapshot)


